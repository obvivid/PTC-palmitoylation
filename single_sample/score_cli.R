# Usage: Rscript single_sample/score_cli.R input.csv output.csv contrast|rank youden|sensitivity95
full <- commandArgs(FALSE); script <- sub('^--file=','',full[grepl('^--file=',full)][1])
directory <- dirname(normalizePath(script,mustWork=TRUE))
args <- commandArgs(trailingOnly=TRUE)
if(length(args)!=4)stop('Supply input CSV, output CSV, score method and operating point.')
source(file.path(directory,'single_sample_score.R'))
source(file.path(directory,'read_frozen_model.R'))
model <- read_frozen_model(directory)
input <- read.csv(args[1],check.names=FALSE,stringsAsFactors=FALSE)
if(!all(c('gene','log2_expression')%in%names(input)))stop('Input columns must include gene and log2_expression.')
if(!is.numeric(input$log2_expression))stop('log2_expression must be numeric.')
result <- score_single_sample(setNames(input$log2_expression,input$gene),model,args[3],args[4])
write.csv(result,args[2],row.names=FALSE)
print(result)
